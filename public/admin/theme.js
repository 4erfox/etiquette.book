/**
 theme.js — управление темой оформления админ-панели
 Хранит цветовые токены (токены дизайн-системы) и функции для переключения между светлой и тёмной темой
 */

// Генерирует объект цветовых токенов для указанной темы (тёмная или светлая)
// Тёмная тема использует светлые цвета на тёмном фоне, светлая — тёмные на светлом
export function makeTokens(isDark) {
  // Тёмная тема: светлые цвета на чёрном фоне для удобства ночью и для глаз
  return isDark ? {
    // Основные цвета фона
    bg:           '#111112',        // главный фон страницы
    surface:      '#18181a',        // фон для панелей и контейнеров
    surfaceHov:   '#1f1f22',        // фон при наведении мыши
    // Границы элементов — полупрозрачные для мягкого контраста
    border:       'rgba(255,255,255,0.09)',  // обычная граница
    borderStrong: 'rgba(255,255,255,0.18)',  // акцентная граница
    // Цвета текста — от базовых до очень приглушённых
    fg:           '#e8e8e8',                 // основной текст
    fgMuted:      'rgba(255,255,255,0.4)',   // приглушённый текст (подписи, описания)
    fgSub:        'rgba(255,255,255,0.2)',   // очень слабый текст (вспомогательные элементы)
    // Дополнительные токены
    accentSoft:   'rgba(255,255,255,0.06)',  // очень мягкий акцент для фонов
    success:      '#22c55e',   // зелёный для успеха и пометок
    danger:       '#ef4444',   // красный для ошибок и опасных действий
    warning:      '#f59e0b',   // оранжевый для предупреждений
    mono:         'ui-monospace,"Cascadia Code","Fira Code",monospace',  // моноширинный шрифт для кода
    shadow:       '0 8px 40px rgba(0,0,0,0.7)',  // тень для модальных окон и попапов
    inpBg:        '#1e1e20',       // фон для input-полей
    inpBorder:    'rgba(255,255,255,0.12)',  // граница input-полей
  } : {
    // Светлая тема: тёмные цвета на белом фоне для работы днём
    // Основные цвета фона
    bg:           '#f0efeb',        // главный фон страницы
    surface:      '#e5e4e0',        // фон для панелей и контейнеров
    surfaceHov:   '#dddcd8',        // фон при наведении мыши
    // Границы элементов — полупрозрачные чёрные для контраста на светлом
    border:       'rgba(0,0,0,0.1)',   // обычная граница
    borderStrong: 'rgba(0,0,0,0.2)',   // акцентная граница
    // Цвета текста — от базовых до очень приглушённых
    fg:           '#111111',            // основной текст
    fgMuted:      'rgba(0,0,0,0.45)',   // приглушённый текст
    fgSub:        'rgba(0,0,0,0.25)',   // очень слабый текст
    // Дополнительные токены
    accentSoft:   'rgba(0,0,0,0.06)',   // очень мягкий акцент для фонов
    success:      '#16a34a',   // более тёмный зелёный для светлой темы
    danger:       '#dc2626',   // более тёмный красный для светлой темы
    warning:      '#d97706',   // более тёмный оранжевый для светлой темы
    mono:         'ui-monospace,"Cascadia Code","Fira Code",monospace',  // моноширинный шрифт
    shadow:       '0 8px 32px rgba(0,0,0,0.18)',  // более мягкая тень на светлом фоне
    inpBg:        '#e8e7e3',       // фон для input-полей
    inpBorder:    'rgba(0,0,0,0.12)',  // граница input-полей
  };
}

// Текущий набор цветовых токенов — инициализируется тёмной темой по умолчанию
let _t = makeTokens(true);
// Набор колбэков которые вызываются при смене темы для обновления интерфейса
const _cbs = new Set();

// Возвращает текущий набор цветовых токенов — используется остальными модулями для стилизации
export function getT() { return _t; }

// Переключает тему на указанную и уведомляет всех подписчиков об изменении
export function setTheme(isDark) {
  _t = makeTokens(isDark);
  _cbs.forEach(fn => fn(_t));
}

// Подписывает функцию на изменения темы и возвращает функцию отписки
export function onThemeChange(fn) {
  _cbs.add(fn);
  return () => _cbs.delete(fn);  // функция отписки удаляет колбэк из набора
}

// Определяет тему из localStorage или HTML-атрибута, иначе возвращает тёмную по умолчанию
// Проверяет в порядке приоритета: 1) localStorage, 2) data-theme на <html>, 3) тёмная по умолчанию
export function detectTheme() {
  // Сначала проверяем что пользователь сохранил в localStorage при предыдущем посещении
  const stored = localStorage.getItem('theme');
  if (stored) return stored !== 'light';
  // Если ничего не сохранено, проверяем атрибут на корневом элементе (может быть установлен сервером)
  const attr = document.documentElement.getAttribute('data-theme');
  if (attr) return attr !== 'light';
  // Если ничего не найдено — используем тёмную тему как безопасный вариант по умолчанию
  return true;
}
