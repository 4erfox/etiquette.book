const categories = ['Все', ...new Set(allCards.map(c => c.category))];
let activeCategory = 'Все';
let currentCards = [...allCards];

// ═══════════════════════════════════════
// РЕНДЕР КАТЕГОРИЙ
// ═══════════════════════════════════════
function renderCategories() {
  const el = document.getElementById('categories');
  el.innerHTML = categories.map(cat => `
    <button class="cat-btn${cat === activeCategory ? ' active' : ''}"
            onclick="setCategory('${cat}')">
      ${cat}
    </button>
  `).join('');
}

function setCategory(cat) {
  activeCategory = cat;
  currentCards = cat === 'Все'
    ? [...allCards]
    : allCards.filter(c => c.category === cat);
  renderCategories();
  renderCards();
}

// ═══════════════════════════════════════
// РЕНДЕР КАРТОЧЕК
// ═══════════════════════════════════════
function renderCards() {
  const grid = document.getElementById('cards-grid');
  const counter = document.getElementById('counter');

  counter.textContent = `${currentCards.length} карточек`;

  if (currentCards.length === 0) {
    grid.innerHTML = '<div class="empty-state">Карточки не найдены</div>';
    return;
  }

  grid.innerHTML = currentCards.map((card, i) => `
    <div class="flip-card" onclick="flip(this)" data-index="${i}">
      <div class="flip-inner">
        <div class="flip-front">
          <div>
            <div class="card-category">${card.category}</div>
            <div class="card-question">${card.q}</div>
          </div>
          <div class="card-hint">
            <svg viewBox="0 0 24 24"><path d="M12 2a10 10 0 1 0 10 10A10 10 0 0 0 12 2zm0 14v-4m0-4h.01"/></svg>
            Нажмите чтобы увидеть ответ
          </div>
        </div>
        <div class="flip-back">
          <div>
            <div class="card-answer-label">Ответ</div>
            <div class="card-answer">${card.a}</div>
          </div>
          <div class="card-tap-again">
            <svg viewBox="0 0 24 24"><polyline points="1 4 1 10 7 10"/><path d="M3.51 15a9 9 0 1 0 .49-4.95"/></svg>
            Нажмите чтобы перевернуть обратно
          </div>
        </div>
      </div>
    </div>
  `).join('');
}

// ═══════════════════════════════════════
// ПЕРЕВОРОТ
// ═══════════════════════════════════════
function flip(card) {
  card.classList.toggle('flipped');
}

// ═══════════════════════════════════════
// ПЕРЕМЕШАТЬ
// ═══════════════════════════════════════
function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

document.getElementById('shuffle-btn').addEventListener('click', () => {
  currentCards = shuffle([...currentCards]);
  renderCards();
});

